// Writes contributes.customEditors of plugin/orca-plugin.json and the text entries in plugin/editor/text/.
//
// Why: Orca offers a `contentKind: "bytes"` editor only for files it judges binary (a NUL byte in the first
// 8 KB, or a suffix Orca previews itself: .png .jpg .gif .svg .webp .bmp .ico .pdf), and a `text` editor
// only for the others; a text document carries no fileType. URDF, xacro, KiCad,
// draw.io, ASCII DXF/STL, STEP, OBJ, SVG … are text, so they need text editors. Orca allows at most 16 editors
// per plugin, so binary suffixes share 6 bytes editors (entry editor/main.ts, dispatch on fileType) and text
// suffixes share 10 text editors, one per format family (entry editor/text/<family>.ts; the viewer tells the
// exact type from the content, see textType() in editor/app.ts). Orca shows exactly one of the two per file.
//
//   node tools/gen-text-editors.mjs          rewrite the manifest editors and the entries
//   node tools/gen-text-editors.mjs --check  fail when they are out of date (unit tests and CI run this)
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const MANIFEST = join(ROOT, 'plugin', 'orca-plugin.json')
const DIR = join(ROOT, 'plugin', 'editor', 'text')

/** Binary documents: one editor per group, all on editor/main.ts. */
export const BYTES_GROUPS = [
  ['office', 'Office · PDF Preview', 'docx doc pptx ppt xlsx xlsm xls ods hwp hwpx pdf'],
  ['media', 'Text · Web · Image Preview', 'txt log csv tsv html htm xhtml svg gif bmp'],
  ['diagram', 'Diagram Preview', 'drawio dio vsdx vsdm vstx vssx'],
  ['model3d', '3D · Robot Preview', 'stl obj ply glb gltf 3mf off fbx dae step stp stpz iges igs brep urdf xacro'],
  ['cad2d', 'CAD Drawing Preview', 'dxf dwf dwfx'],
  ['engineering', 'Engineering Preview', 'kicad_sch kicad_pcb kicad_mod kicad_sym kicad_pro kicad_wks sldprt sldasm slddrw slddrt prtdot asmdot drwdot elk ell elr els elp elx ela zw1 zx1 edz ema emp']
]

/** Text documents: one editor per family, entry editor/text/<family>.ts. */
export const TEXT_FAMILIES = [
  ['text', 'Text Preview', 'txt log'],
  ['csv', 'Table Preview', 'csv tsv'],
  ['web', 'HTML Preview', 'html htm xhtml'],
  ['diagram', 'Diagram Preview', 'drawio dio'],
  ['model3d', '3D Preview', 'stl obj ply gltf off fbx dae step stp iges igs brep'],
  ['kicad', 'KiCad Preview', 'kicad_sch kicad_pcb kicad_mod kicad_sym kicad_pro kicad_wks'],
  ['dxf', 'CAD Drawing Preview', 'dxf'],
  ['robot', 'Robot Preview', 'urdf xacro'],
  ['office', 'Office Preview', 'doc xls'],
  ['eplan', 'EPLAN Macro Preview', 'ema emp']
]

const exts = (s) => s.split(' ').map((x) => `.${x}`)
const editors = [
  ...BYTES_GROUPS.map(([id, title, list]) => ({ id, title, extensions: exts(list), entry: 'editor/main.ts', contentKind: 'bytes', frame: 'any' })),
  ...TEXT_FAMILIES.map(([id, title, list]) => ({ id: `${id}-text`, title, extensions: exts(list), entry: `editor/text/${id}.ts`, contentKind: 'text', frame: 'any' }))
]
const entries = new Map(
  TEXT_FAMILIES.map(([id, title, list]) => [
    `${id}.ts`,
    `// Generated by tools/gen-text-editors.mjs: the ${title} for files Orca sends as text (${exts(list).join(' ')}).\nimport { boot } from '../app.ts'\n\nboot('${id}')\n`
  ])
)

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'))
const check = process.argv.includes('--check')
let ok = JSON.stringify(manifest.contributes.customEditors) === JSON.stringify(editors)
try {
  const have = readdirSync(DIR).filter((f) => f.endsWith('.ts'))
  ok &&= have.length === entries.size && have.every((f) => entries.get(f) === readFileSync(join(DIR, f), 'utf8'))
} catch {
  ok = false
}
if (check) {
  if (!ok) {
    console.error('custom editors are out of date: run node tools/gen-text-editors.mjs')
    process.exit(1)
  }
  console.log(`custom editors up to date (${editors.length})`)
  process.exit(0)
}
if (editors.length > 16) throw new Error(`Orca allows at most 16 custom editors (have ${editors.length})`)
manifest.contributes.customEditors = editors
writeFileSync(MANIFEST, JSON.stringify(manifest, null, 2) + '\n')
rmSync(DIR, { recursive: true, force: true })
mkdirSync(DIR, { recursive: true })
for (const [f, body] of entries) writeFileSync(join(DIR, f), body)
console.log(`wrote ${editors.length} custom editors (${BYTES_GROUPS.length} bytes, ${TEXT_FAMILIES.length} text) and ${entries.size} text entries`)
