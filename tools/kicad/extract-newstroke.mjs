// Extracts a subset of the newstroke stroke font (KiCad's default font) into
// plugin/editor/renderers/kicad/newstroke.ts.
//
// Source: KiCanvas (MIT, https://github.com/theacodes/kicanvas) src/kicad/text/newstroke-glyphs.ts,
// a JS conversion of newstroke_font.cpp. The glyph data of the Latin/Greek/Cyrillic/symbol ranges
// kept here is Vladimir Uryvaev's newstroke font, released under CC0 (third_party/newstroke/README.txt
// in KiCanvas). The CJK glyphs (Source Han Sans, OFL) are NOT extracted; CJK text falls back to a
// system font in the renderer.
//
//   git clone --depth 1 https://github.com/theacodes/kicanvas .orca/ext/kicanvas
//   node tools/kicad/extract-newstroke.mjs [path/to/newstroke-glyphs.ts]
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const src = process.argv[2] ?? join(root, '.orca/ext/kicanvas/src/kicad/text/newstroke-glyphs.ts')
const text = readFileSync(src, 'utf8')
const grab = (name) => {
  const i = text.indexOf(`export const ${name}`)
  const s = text.indexOf('[', text.indexOf('=', i))
  let depth = 0
  for (let j = s; j < text.length; j++) {
    const c = text[j]
    if (c === '"') {
      j++
      while (text[j] !== '"') j += text[j] === '\\' ? 2 : 1
    } else if (c === '[') depth++
    else if (c === ']' && --depth === 0) return JSON.parse(text.slice(s, j + 1))
  }
  throw new Error(name)
}
const shared = grab('shared_glyphs')
const data = grab('glyph_data')
// Code point ranges kept (inclusive).
const RANGES = [
  [0x20, 0x24f], // ASCII, Latin-1, Latin Extended-A/B
  [0x370, 0x4ff], // Greek, Cyrillic
  [0x2010, 0x2044], // dashes, quotes, bullets, ellipsis, primes
  [0x20ac, 0x20ac], // euro
  [0x2100, 0x2135], // letterlike (Ω ℃ №)
  [0x2190, 0x21ff], // arrows
  [0x2200, 0x22ff], // math operators
  [0x2300, 0x23ff], // misc technical (⌀)
  [0x25a0, 0x25ff] // geometric shapes
]
const out = {}
const usedShared = new Set()
for (const [a, b] of RANGES) {
  for (let cp = a; cp <= b; cp++) {
    const g = data[cp - 0x20]
    if (g == null) continue
    if (typeof g === 'number') {
      usedShared.add(g)
      out[cp] = g
    } else out[cp] = g
  }
}
const lines = [
  '/* Newstroke stroke font subset (KiCad default font). Glyph data by Vladimir Uryvaev and KiCad',
  ' * contributors, released under CC0 1.0; converted to JS by KiCanvas (MIT, (c) 2023 Alethea',
  ' * Katherine Flowers). Generated by tools/kicad/extract-newstroke.mjs. Coordinates are pairs of',
  ' * characters relative to "R"; the first pair is the left/right extent, " R" ends a stroke. */',
  '/** Shared glyphs referenced by number from GLYPHS. */',
  `export const SHARED: string[] = ${JSON.stringify(shared)}`,
  '/** Code point to glyph (string) or SHARED index (number). */',
  `export const GLYPHS: Record<number, string | number> = ${JSON.stringify(out)}`,
  ''
]
const dst = join(root, 'plugin/editor/renderers/kicad/newstroke.ts')
writeFileSync(dst, lines.join('\n'))
console.log(`${Object.keys(out).length} glyphs, ${shared.length} shared → ${dst} (${lines.join('\n').length} bytes)`)
