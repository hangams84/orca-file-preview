// Downloads the pinned third-party fidelity corpus (tools/fidelity/sources.json) into
// samples/fidelity/<fmt>/ and writes samples/fidelity/NOTICE.md with sources, licenses and hashes.
//   node tools/fidelity/fetch-corpus.mjs
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const OUT = join(ROOT, 'samples', 'fidelity')
const src = JSON.parse(readFileSync(join(ROOT, 'tools', 'fidelity', 'sources.json'), 'utf8'))
const rows = []
for (const f of src.files) {
  const repo = src.repos[f.repo]
  const [, owner, name] = repo.url.match(/github\.com\/([^/]+)\/([^/]+)/)
  const url = `https://raw.githubusercontent.com/${owner}/${name}/${repo.commit}/${f.path.split('/').map(encodeURIComponent).join('/')}`
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${res.status} ${url}`)
  const buf = Buffer.from(await res.arrayBuffer())
  const dest = join(OUT, f.as)
  mkdirSync(dirname(dest), { recursive: true })
  writeFileSync(dest, buf)
  const sha = createHash('sha256').update(buf).digest('hex')
  rows.push(`| \`${f.as}\` | [${f.path}](${repo.url}/blob/${repo.commit}/${f.path.split('/').map(encodeURIComponent).join('/')}) | ${repo.license} | ${f.why} | \`${sha.slice(0, 16)}\` |`)
  console.log(`${String(buf.length).padStart(9)}  ${f.as}`)
}
writeFileSync(
  join(OUT, 'NOTICE.md'),
  [
    '# Fidelity corpus — third-party test documents',
    '',
    'These files are copied unchanged from the projects below, at the pinned commits, under their',
    'licenses (Apache License 2.0). They are used only as test inputs. Files whose names start with',
    '`word-` are generated by `tools/fidelity/make-doc-fixtures.ps1` for this project.',
    '',
    ...Object.entries(src.repos).map(([k, r]) => `- **${k}**: ${r.url} @ \`${r.commit}\` (${r.license})`),
    '',
    '| File | Source | License | Purpose | SHA-256 (prefix) |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
    ''
  ].join('\n')
)
console.log(`${rows.length} files → samples/fidelity/ (NOTICE.md written)`)
