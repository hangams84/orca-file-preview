// Bundles third-party libraries into self-contained ESM files under vendor/, because Orca plugin
// frames have no network and no bare-package imports. Each tools/vendor/<name>.entry.js becomes
// vendor/<name>.js. Run `npm run vendor` after changing an entry or a dependency version; the
// outputs are committed so the plugin itself needs no build step.
import { build } from 'esbuild'
import { copyFileSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const entriesDir = join(root, 'tools', 'vendor')
const outDir = join(root, 'plugin', 'vendor')
mkdirSync(outDir, { recursive: true })

const entries = readdirSync(entriesDir).filter((f) => f.endsWith('.entry.js'))
const report = []
for (const file of entries) {
  const name = file.replace(/\.entry\.js$/, '')
  const outfile = join(outDir, `${name}.js`)
  await build({
    entryPoints: [join(entriesDir, file)],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: ['chrome110', 'safari16', 'firefox115'],
    minify: true,
    legalComments: 'eof',
    define: { 'process.env.NODE_ENV': '"production"', global: 'globalThis' },
    logLevel: 'warning'
  })
  report.push([`${name}.js`, statSync(outfile).size])
}

// Files copied as-is (already ESM, loaded separately such as a Web Worker script).
const copies = [['node_modules/pdfjs-dist/legacy/build/pdf.worker.min.mjs', 'pdf.worker.min.js']]
for (const [from, to] of copies) {
  try {
    copyFileSync(join(root, from), join(outDir, to))
    report.push([to, statSync(join(outDir, to)).size])
  } catch {
    // dependency not installed yet: skip
  }
}

// pdf.js data files fetched at run time: cMaps (CJK CID fonts), standard fonts, image decoders.
const pdfDist = join(root, 'node_modules/pdfjs-dist')
const pdfAssets = [
  ['cmaps', (f) => f.endsWith('.bcmap') || f === 'LICENSE'],
  ['standard_fonts', () => true],
  ['wasm', (f) => !f.includes('quickjs')]
]
for (const [dir, keep] of pdfAssets) {
  try {
    const files = readdirSync(join(pdfDist, dir)).filter(keep)
    mkdirSync(join(outDir, 'pdf-assets', dir), { recursive: true })
    let size = 0
    for (const f of files) {
      copyFileSync(join(pdfDist, dir, f), join(outDir, 'pdf-assets', dir, f))
      size += statSync(join(outDir, 'pdf-assets', dir, f)).size
    }
    report.push([`pdf-assets/${dir}/ (${files.length} files)`, size])
  } catch {
    // dependency not installed yet: skip
  }
}

writeFileSync(
  join(outDir, 'README.md'),
  '# vendor\n\nGenerated by `npm run vendor` (tools/build-vendor.mjs). Do not edit by hand.\n\n' +
    report.map(([f, s]) => `- \`${f}\` — ${(s / 1024).toFixed(0)} KB`).join('\n') +
    '\n'
)
for (const [f, s] of report) console.log(`${f.padEnd(28)} ${(s / 1024).toFixed(0).padStart(6)} KB`)
