// Packs a few small samples from samples/ai-formats/ and their Python ground truth into
// plugin/editor/renderers/aimodel/formats/fixtures.ts (one zlib-compressed base64 blob) for the
// plugin's unit tests (formats.test.ts). Rerun after tools/make-ai-format-samples.py.
//
//   node tools/ai-formats/make-unit-fixtures.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { deflateSync } from 'node:zlib'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const DIR = join(ROOT, 'samples', 'ai-formats')
const OUT = join(ROOT, 'plugin', 'editor', 'renderers', 'aimodel', 'formats', 'fixtures.ts')
const FILES = {
  numpy: ['np-struct.npy', 'np-i64be.npy', 'np-fortran.npy', 'np-f16.npy', 'np-unicode.npy', 'np-compressed.npz', 'np-stored.npz'],
  onnx: ['onnx-control-flow.onnx', 'onnx-mlp.onnx'],
  tflite: ['tflite-int8.tflite', 'tflite-control-flow.tflite'],
  gguf: ['gguf-unit.gguf'],
  hdf5: ['hdf5-v3.h5'],
  keras: ['keras-functional.keras']
}
const truth = JSON.parse(readFileSync(join(DIR, 'truth.json'), 'utf8'))
const parts = []
const index = {}
const expect = {}
let off = 0
for (const [fmt, names] of Object.entries(FILES)) {
  for (const n of names) {
    const b = readFileSync(join(DIR, n))
    index[n] = [off, b.length]
    parts.push(b)
    off += b.length
    expect[n] = truth[fmt][n]
  }
}
const files = Buffer.concat(parts)
const json = Buffer.from(JSON.stringify({ index, expect }), 'utf8')
const head = Buffer.alloc(4)
head.writeUInt32LE(json.length)
const blob = deflateSync(Buffer.concat([head, json, files]), { level: 9 }).toString('base64')
const lines = blob.match(/.{1,120}/g).map((l) => `  '${l}'`).join(' +\n')
writeFileSync(
  OUT,
  `/** GENERATED by tools/ai-formats/make-unit-fixtures.mjs: ${Object.values(FILES).flat().join(', ')}
 *  from samples/ai-formats/ (written by tools/make-ai-format-samples.py) and their Python ground truth,
 *  zlib-compressed. Used by formats.test.ts only. */
import { unzlibSync } from '../../../../vendor/zip.js'

const B64 =
${lines}

export interface Fixtures {
  file(name: string): Uint8Array
  expect: Record<string, any> // eslint-disable-line @typescript-eslint/no-explicit-any
  names: string[]
}

let cache: Fixtures | null = null

export function fixtures(): Fixtures {
  if (cache) return cache
  const all = unzlibSync(Uint8Array.from(atob(B64), (c) => c.charCodeAt(0)))
  const n = new DataView(all.buffer, all.byteOffset).getUint32(0, true)
  const meta = JSON.parse(new TextDecoder().decode(all.subarray(4, 4 + n)))
  const base = 4 + n
  cache = {
    file: (name) => {
      const [o, len] = meta.index[name]
      return all.slice(base + o, base + o + len)
    },
    expect: meta.expect,
    names: Object.keys(meta.index)
  }
  return cache
}
`
)
console.log(`${OUT}: ${files.length} bytes of samples + ${json.length} bytes of truth → ${blob.length} base64 chars`)
