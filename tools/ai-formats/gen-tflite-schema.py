"""Generates plugin/editor/renderers/aimodel/formats/tflite-schema.ts from TensorFlow's own
tensorflow/lite/python/schema_py_generated.py (the flatc output of schema.fbs): the complete
BuiltinOperator and TensorType enums and, for every builtin-options table, its fields (vtable slot,
scalar type, default). Rerun after a TensorFlow upgrade:

  .orca/venv/Scripts/python tools/ai-formats/gen-tflite-schema.py
"""
import json
import re
from pathlib import Path

from tensorflow.lite.python import schema_py_generated as schema

SRC = Path(schema.__file__).read_text(encoding="utf-8")
OUT = Path(__file__).resolve().parents[2] / "plugin" / "editor" / "renderers" / "aimodel" / "formats" / "tflite-schema.ts"

FLAGS = {"Bool": "bool", "Int8": "i8", "Uint8": "u8", "Int16": "i16", "Uint16": "u16", "Int32": "i32", "Uint32": "u32", "Int64": "i64", "Uint64": "u64", "Float32": "f32", "Float64": "f64"}


def enum(cls):
    vals = {k: v for k, v in vars(cls).items() if not k.startswith("_") and isinstance(v, int)}
    out = [""] * (max(vals.values()) + 1)
    for k, v in sorted(vals.items(), key=lambda kv: kv[1]):
        if v >= 0 and not out[v]:
            out[v] = k
    return out


def classes():
    """class name → source text."""
    parts = re.split(r"^class (\w+)\(object\):\n", SRC, flags=re.M)
    return {parts[i]: parts[i + 1] for i in range(1, len(parts), 2)}


def fields(body):
    out = []
    for m in re.finditer(r"    def (\w+)\(self(, j)?\):\n(.*?)(?=\n    def |\Z)", body, flags=re.S):
        name, vec, code = m.group(1), m.group(2), m.group(3)
        if name.endswith(("Length", "IsNone", "AsNumpy")) or name.startswith(("GetRootAs", "Init")):
            continue
        off = re.search(r"Offset\((\d+)\)", code)
        if not off:
            continue
        slot = (int(off.group(1)) - 4) // 2
        flag = re.search(r"number_types\.(\w+)Flags, ", code)
        if "self._tab.String(" in code:
            kind = "str"
        elif flag and flag.group(1) in FLAGS:
            kind = FLAGS[flag.group(1)]
        else:
            continue  # nested tables / unions: not shown
        if vec:
            kind = f"[{kind}]"
        default = re.findall(r"^        return (.+)$", code, flags=re.M)
        d = default[-1].strip() if default and not vec else None
        try:
            d = json.loads(d.replace("False", "false").replace("True", "true")) if d is not None else None
        except Exception:
            d = None
        out.append([re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower(), slot, kind, d])
    return out


def main():
    cls = classes()
    ops = enum(schema.BuiltinOperator)
    types = enum(schema.TensorType)
    union = enum(schema.BuiltinOptions)
    union2 = enum(schema.BuiltinOptions2) if hasattr(schema, "BuiltinOptions2") else []
    act = enum(schema.ActivationFunctionType)
    pad = enum(schema.Padding)

    def table(names):
        res = []
        for n in names:
            if not n or n == "NONE" or n not in cls:
                res.append(None)
                continue
            res.append([n, fields(cls[n])])
        return res

    ts = [
        "/** GENERATED by tools/ai-formats/gen-tflite-schema.py from TensorFlow's schema_py_generated.py",
        " *  (flatc output of tensorflow/lite/schema/schema.fbs). Do not edit. */",
        "",
        "/** BuiltinOperator: index = builtin code. */",
        f"export const BUILTIN_OPS: string[] = {json.dumps(ops)}",
        "",
        "/** TensorType: index = type id. */",
        f"export const TENSOR_TYPES: string[] = {json.dumps(types)}",
        "",
        f"export const ACTIVATIONS: string[] = {json.dumps(act)}",
        f"export const PADDINGS: string[] = {json.dumps(pad)}",
        "",
        "/** One options field: [snake_case name, vtable slot, scalar type ('[t]' = vector), default]. */",
        "export type OptionField = [string, number, string, number | boolean | null]",
        "",
        "/** BuiltinOptions union: index = union type → [table name, fields]. */",
        f"export const BUILTIN_OPTIONS: ([string, OptionField[]] | null)[] = {json.dumps(table(union), separators=(',', ':'))}",
        "",
        "/** BuiltinOptions2 union (StableHLO and newer ops). */",
        f"export const BUILTIN_OPTIONS_2: ([string, OptionField[]] | null)[] = {json.dumps(table(union2), separators=(',', ':'))}",
        "",
    ]
    OUT.write_text("\n".join(ts), encoding="utf-8")
    print(OUT, OUT.stat().st_size, "bytes;", len(ops), "ops;", len(types), "types;", len(union), "+", len(union2), "options")


if __name__ == "__main__":
    main()
