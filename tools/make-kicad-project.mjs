/** A placed symbol; `refs` maps instance paths to references. */
function sym(lib, x, y, uuid, ownRef, value, refs) {
  const inst = refs.map(([path, ref]) => `(path "${path}" (reference "${ref}") (unit 1))`).join(' ')
  return `  (symbol (lib_id "Demo:${lib}") (at ${x} ${y} 0) (unit 1) (exclude_from_sim no) (in_bom yes) (on_board yes) (dnp no)
    (uuid "${uuid}")
    (property "Reference" "${ownRef}" (at ${x + 2.54} ${y - 1.27} 0) (effects (font (size 1.27 1.27)) (justify left)))
    (property "Value" "${value}" (at ${x + 2.54} ${y + 1.27} 0) (effects (font (size 1.27 1.27)) (justify left)))
    (property "Footprint" "" (at ${x} ${y} 0) (effects (font (size 1.27 1.27)) hide))
    (property "Datasheet" "~" (at ${x} ${y} 0) (effects (font (size 1.27 1.27)) hide))
    (pin "1" (uuid "${uuid.slice(0, -2)}f1"))
    (pin "2" (uuid "${uuid.slice(0, -2)}f2"))
    (instances (project "demo" ${inst})))
`
}

function sheet(x, y, w, hh, uuid, name, file, parentPath, page) {
  return `  (sheet (at ${x} ${y}) (size ${w} ${hh}) (fields_autoplaced yes)
    (stroke (width 0.1524) (type solid)) (fill (color 0 0 0 0.0000))
    (uuid "${uuid}")
    (property "Sheetname" "${name}" (at ${x} ${y - 0.7} 0) (effects (font (size 1.27 1.27)) (justify left bottom)))
    (property "Sheetfile" "${file}" (at ${x} ${y + hh + 0.6} 0) (effects (font (size 1.27 1.27)) (justify left top)))
    (instances (project "demo" (path "${parentPath}" (page "${page}")))))
`
}

const wire = (x0, y0, x1, y1, n) => `  (wire (pts (xy ${x0} ${y0}) (xy ${x1} ${y1})) (stroke (width 0) (type default)) (uuid "${u(n)}"))\n`
