// Writes samples/kicad-project/: a small hierarchical KiCad 8 project for the companion-file tests (MIT, generated).
//
//   demo.kicad_pro      project; schematic drawing sheet = demo.kicad_wks; text variable PROJECT_CODE
//   demo.kicad_sch      root: sheets "Channel A" and "Channel B" (both channel.kicad_sch) and "Power" (power.kicad_sch)
//   channel.kicad_sch   R + C; per-instance references R101/C101 (Channel A) and R201/C201 (Channel B)
//   power.kicad_sch     one R and a nested sheet "Regulator" (regulator.kicad_sch)
//   regulator.kicad_sch one C
//   demo.kicad_wks      a custom drawing sheet (frame, grid labels, a title block using ${TITLE} ${PROJECT_CODE} ${#}/${##})
//
//   node tools/make-kicad-project.mjs
// Check with KiCad: kicad-cli sch export svg samples/kicad-project/demo.kicad_sch -o <dir>
